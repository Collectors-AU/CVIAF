#!/usr/bin/env python3
"""Freeze, shard and reconcile CVIAF corpus jobs. Run from the repository root.

Requires the benchmark venv (numpy and project dependencies). No training is
started by this tool. Do not publish a merged corpus until verify returns zero.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys

# Direct script execution sets sys.path[0] to scripts/, not the checkout root.
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from cviaf.lab.corpus import build_specs, load_plan


def digest(path):
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        for block in iter(lambda: f.read(1024 * 1024), b''):
            h.update(block)
    return h.hexdigest()


def write_json(path, obj):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + '.tmp')
    tmp.write_text(json.dumps(obj, indent=2, sort_keys=True) + '\n')
    os.replace(tmp, path)


def assert_checkout(commit):
    actual = subprocess.check_output(['git', 'rev-parse', 'HEAD'], text=True).strip()
    if actual != commit:
        raise ValueError(f'checkout HEAD {actual} differs from pinned {commit}')


def freeze(a):
    assert_checkout(a.source_commit)
    plan = load_plan(a.plan)
    specs = build_specs(plan)
    ids = [s.model_id for s in specs]
    if len(ids) != len(set(ids)):
        raise ValueError('duplicate model IDs in plan; adjust attack recipes before sharding')
    # One seed per shard by default, or seed/attack group for more workers.
    groups = a.groups
    if groups < 1:
        raise ValueError('groups must be positive')
    if a.source_commit == '':
        raise ValueError('pass the pinned, integrated source commit')
    root = Path(a.out)
    if root.exists() and any(root.iterdir()):
        raise ValueError(f'{root} must be empty; never overwrite a frozen run')
    root.mkdir(parents=True, exist_ok=True)
    shards = []
    # Greedy round-robin over attack indices, preserving clean per seed in every
    # shard only when assigned: the global merge always retains all clean controls.
    for seed in plan['seeds']:
        for group in range(groups):
            selected = [atk for i, atk in enumerate(plan['attacks']) if i % groups == group]
            if not selected:
                continue
            name = f'seed-{seed}-group-{group}'
            subplan = {**plan, 'name': name, 'seeds': [seed], 'attacks': selected,
                       'out': f'shards/{name}/corpus'}
            write_json(root / 'plans' / (name + '.json'), subplan)
            subids = [s.model_id for s in build_specs(subplan)]
            shards.append({'name': name, 'model_ids': subids,
                           'plan': f'plans/{name}.json', 'out': subplan['out']})
    covered = [i for s in shards for i in s['model_ids']]
    if len(covered) != len(ids) or set(covered) != set(ids):
        raise AssertionError('shards do not partition model IDs')
    expected = {s.model_id: {'spec_digest': s.digest(),
                             'scene_seed': s.scene.seed,
                             'attack_seed': s.attack.seed,
                             'detector_seed': s.detector.seed,
                             'kind': s.attack.kind} for s in specs}
    write_json(root / 'plan.json', plan)
    plan_sha = digest(root / 'plan.json')
    manifest = {'format': 1, 'source_commit': a.source_commit,
                'plan_sha256': plan_sha, 'source_plan': a.plan,
                'model_count': len(ids), 'expected': expected,
                'shards': shards,
                'evaluation_seeds': {'compare': 1, 'eval': 1},
                'evaluation_options': {'alpha': 0.05, 'backgrounds': 8,
                                       'ftc_stride': 8, 'ftc_decoy_class': 0}}
    write_json(root / 'frozen.json', manifest)
    print(f'frozen {len(ids)} models in {len(shards)} shards: {root}')
    for s in shards:
        print(f"{s['name']}: {len(s['model_ids'])} models, plan {s['plan']}")


def verify(a):
    assert_checkout(a.source_commit)
    root = Path(a.root)
    frozen = json.loads((root / 'frozen.json').read_text())
    if digest(root / 'plan.json') != frozen['plan_sha256']:
        raise ValueError('effective plan changed since freeze')
    expected = frozen['expected']
    if len(expected) != frozen['model_count']:
        raise ValueError('invalid frozen model count')
    if a.source_commit != frozen['source_commit']:
        raise ValueError('source commit does not match frozen manifest')
    # Rebuild specs on this checkout; confirms freeze was generated by exactly
    # this implementation and same effective plan, not merely copied metadata.
    plan = json.loads((root / 'plan.json').read_text())
    rebuilt = {s.model_id: s.digest() for s in build_specs(plan)}
    if rebuilt != {k: v['spec_digest'] for k, v in expected.items()}:
        raise ValueError('current build_specs differs from the frozen manifest')
    collected = {}
    inventory = {}
    for shard in frozen['shards']:
        sroot = root / shard['out']
        if not sroot.is_dir():
            raise ValueError(f'missing shard {sroot}')
        expected_here = set(shard['model_ids'])
        actual_here = {p.name for p in sroot.iterdir() if p.is_dir()}
        if actual_here != expected_here:
            raise ValueError(f"{shard['name']}: missing {sorted(expected_here - actual_here)}, extra {sorted(actual_here - expected_here)}")
        for mid in sorted(expected_here):
            if mid in collected:
                raise ValueError(f'duplicate model {mid}')
            model_dir = sroot / mid
            mpath = model_dir / 'manifest.json'
            wpath = model_dir / 'weights.npz'
            if not wpath.is_file():
                raise ValueError(f'missing weights {wpath}')
            m = json.loads(mpath.read_text())
            e = expected[mid]
            if m.get('model_id') != mid or m.get('spec_digest') != e['spec_digest']:
                raise ValueError(f'{mid}: model ID or spec digest mismatch')
            seeds = m.get('seeds', {})
            if seeds != {'scene': e['scene_seed'], 'attack': e['attack_seed'],
                         'detector': e['detector_seed']}:
                raise ValueError(f'{mid}: seed registry mismatch')
            if m.get('ground_truth', {}).get('kind') != e['kind']:
                raise ValueError(f'{mid}: attack kind mismatch')
            if not m.get('dataset_digests') or not m.get('artifact', {}).get('weights_digest'):
                raise ValueError(f'{mid}: missing evidence digests')
            if m.get('spec', {}).get('model_id') != mid:
                raise ValueError(f'{mid}: manifest spec identity mismatch')
            # Verify semantic weight digest too, not only transport checksum.
            from cviaf.lab.detector import TinyDetector
            if TinyDetector.load(str(wpath)).digest() != m['artifact']['weights_digest']:
                raise ValueError(f'{mid}: weights digest mismatch')
            collected[mid] = model_dir
            inventory[mid] = {'shard': shard['name'],
                              'manifest_sha256': digest(mpath),
                              'weights_sha256': digest(wpath),
                              'weights_digest': m['artifact']['weights_digest']}
    if set(collected) != set(expected):
        raise ValueError(f'missing {sorted(set(expected) - set(collected))}')
    if not a.merge:
        print(f'verified {len(collected)} models across {len(frozen["shards"])} shards')
        return
    out = root / 'merged'
    if out.exists():
        raise ValueError(f'{out} exists; refusing to overwrite')
    staging = root / 'merged.tmp'
    if staging.exists():
        raise ValueError(f'{staging} exists; inspect and clear prior incomplete merge')
    staging.mkdir()
    entries = []
    try:
        for mid in sorted(collected):
            dst = staging / mid
            shutil.copytree(collected[mid], dst)
            if digest(dst / 'manifest.json') != inventory[mid]['manifest_sha256'] or digest(dst / 'weights.npz') != inventory[mid]['weights_sha256']:
                raise ValueError(f'{mid}: copy checksum mismatch')
            entries.append({'dir': str(out / mid), 'manifest': json.loads((dst / 'manifest.json').read_text())})
        # Registry is rebuilt once, without stale resumable append entries.
        with open(staging / 'registry.jsonl', 'w') as fh:
            for entry in entries:
                fh.write(json.dumps(entry) + '\n')
        write_json(staging / 'inventory.json', {'source_commit': frozen['source_commit'],
                   'plan_sha256': frozen['plan_sha256'], 'models': inventory})
        os.replace(staging, out)
    except Exception:
        shutil.rmtree(staging, ignore_errors=True)
        raise
    print(f'merged and verified {len(entries)} models: {out}')


def main():
    p = argparse.ArgumentParser(description=__doc__)
    sub = p.add_subparsers(dest='cmd', required=True)
    f = sub.add_parser('freeze')
    f.add_argument('--plan', required=True)
    f.add_argument('--out', required=True)
    f.add_argument('--source-commit', required=True)
    f.add_argument('--groups', type=int, default=1, help='attack groups per seed')
    v = sub.add_parser('verify')
    v.add_argument('--root', required=True)
    v.add_argument('--source-commit', required=True)
    v.add_argument('--merge', action='store_true')
    a = p.parse_args()
    try:
        (freeze if a.cmd == 'freeze' else verify)(a)
    except (OSError, ValueError, AssertionError, KeyError, subprocess.CalledProcessError) as exc:
        p.exit(1, f'ERROR: {exc}\n')


if __name__ == '__main__':
    main()
